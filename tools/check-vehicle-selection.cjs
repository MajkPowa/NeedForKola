'use strict';
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.NFW_BASE_URL || 'http://127.0.0.1:8765';
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
    const errors = [];
    page.on('pageerror', e=>errors.push(e.message));
    const open = query => page.goto(base+'/konfigurator.html?'+query,{waitUntil:'domcontentloaded'});
    const state = () => page.evaluate(()=>Object.fromEntries(new URLSearchParams(location.hash.slice(1))));
    await open('brand=bmw&model=x5&year=2020&view=car');
    assert.equal((await state()).generation,'g05');
    assert.match(await page.locator('.vehicle-render').getAttribute('src'),/g05/);
    const years = await page.locator('#vehicleYear option').evaluateAll(xs=>xs.map(x=>Number(x.value)));
    assert.equal(Math.min(...years),1999);assert.equal(Math.max(...years),2026);
    await open('brand=bmw&model=x5&year=2020&generation=g05&body=wagon&view=car');
    assert.equal((await state()).generation,'');
    assert.equal(await page.locator('.vehicle-render').count(),0);
    await page.reload({waitUntil:'domcontentloaded'});
    assert.equal((await state()).generation,'','An unresolved shared state remains unresolved on reload');
    assert.equal(await page.locator('.vehicle-render').count(),0);
    await page.selectOption('#vehicleBody','suv');
    assert.equal((await state()).generation,'g05');
    await open('brand=bmw&model=x5&year=2020&generation=bogus&body=suv&view=car');
    assert.equal(await page.locator('#vehicleGeneration').inputValue(),'');
    assert.equal(await page.locator('.vehicle-render').count(),0);
    await page.selectOption('#vehicleGeneration','g05');
    assert.match(await page.locator('.vehicle-render').getAttribute('src'),/g05/);
    await open('brand=bmw&model=x5&year=2027&view=car');
    assert.equal((await state()).year,'0');
    assert.equal(await page.locator('.vehicle-render').count(),0);
    assert.match(await page.locator('.vehicle-warning').first().innerText(),/nemáme doložené/);
    await open('brand=ford&model=puma&year=2010&view=car');
    assert.equal((await state()).year,'2010');
    assert.equal((await state()).generation,'');
    assert.equal(await page.locator('#vehicleBody').isDisabled(),true);
    console.log('PASS exact year ranges, missing-year gaps, contradictory/unknown variant links and persistent explicit choice');

    await open('brand=skoda&model=superb&year=2023');
    await page.selectOption('#vehicleBody','wagon');
    const fourth = await page.locator('#vehicleGeneration option').evaluateAll(xs=>xs.find(x=>x.textContent.includes('IV'))?.value);
    assert.ok(fourth);await page.selectOption('#vehicleGeneration',fourth);
    const selected = await state();
    assert.equal(selected.body,'wagon');
    await page.locator('[data-step="5"]').click();
    const spec = await page.locator('.spec').first().innerText();
    assert.match(spec,/Superb/);assert.match(spec,/IV/);assert.match(spec,/Kombi/);
    await page.reload({waitUntil:'domcontentloaded'});
    assert.equal((await state()).generation,selected.generation);
    assert.equal((await state()).body,'wagon');
    await page.locator('[data-step="1"]').click();
    await page.selectOption('#vehicleBody','liftback');
    const lift = await page.locator('#vehicleGeneration option').allTextContents();
    assert.ok(lift.every(x=>!x.includes('IV')),'Superb IV liftback starts 2024, not 2023');
    await page.selectOption('#vehicleYear','2024');
    assert.ok((await page.locator('#vehicleGeneration option').allTextContents()).some(x=>x.includes('IV')));
    await page.selectOption('#vehicleModel','fabia');
    const fabiaBodies = await page.locator('#vehicleBody option').evaluateAll(xs=>xs.map(x=>x.value));
    assert.ok(!fabiaBodies.includes('wagon'),'Fabia Combi ended before 2024');
    console.log('PASS body-specific generation years, model reset and exact summary/URL roundtrip');

    await open('brand=bmw&model=x5&year=2026&generation=generation-5&body=suv&view=car');
    assert.match(await page.locator('.generation-info').innerText(),/Oznámené/);
    assert.equal(await page.locator('.vehicle-render').count(),0,'Announced X5 cannot reuse G05 imagery');
    await page.setViewportSize({width:390,height:844});
    await page.locator('#vehicleBrand').scrollIntoViewIfNeeded();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:require('node:path').join(__dirname,'../docs/qa/vehicle-selection-mobile.png')});
    assert.deepEqual(errors,[]);
    console.log('PASS announced 2026 variants, asset boundaries and mobile selection');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
